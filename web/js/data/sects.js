DATA.sectReq = star => (CFG.sect.REQ_REALM || [])[star - 1] !== undefined ? CFG.sect.REQ_REALM[star - 1] : Math.min(DATA.realms.length - 1, (star - 1) * 2); // -1 = 凡人
const EL_ID = { 金: "jin", 木: "mu", 水: "shui", 火: "huo", 土: "tu", 雷: "lei" };

DATA.sects = [];
DATA.sectById = {};
SECT_NAMES.forEach((list, i) => {
  const star = i + 1;
  list.forEach(([prefix, name, el], j) => {
    const sect = {
      id: `s${star}_${j}`, star, prefix, name, el: EL_ID[el],
      reqRealm: DATA.sectReq(star),
    };
    const nm = (CFG.names.sect || {})[sect.id];   // 名字在 config/names.js 的 sect：[功法名前缀, 门派名]
    if (nm) { sect.prefix = DATA.nmPick(nm, 0, prefix); sect.name = DATA.nmPick(nm, 1, name); }
    DATA.sects.push(sect);
    DATA.sectById[sect.id] = sect;
  });
});

