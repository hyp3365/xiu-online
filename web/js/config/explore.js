CFG.explore = {
  TIME: 100,         // 每次历练 / 自动探索走多少步
  END_WAIT: 3,       // v203 走完最后一步后固定再等几秒才结算、开始下一次（历练 / 探索 / 出窍 / 秘境 / 灵地都用；「神行」不影响）
  STEP_SEC: 3,       // 每走一步的秒数（宗门秘法「神行」可减少）
  STEP_MIN: 0.1,     // 每步最少秒数（「神行」减到这里为止）
  STOP: 0.3,         // 生命低于上限这个比例（0.3 = 30%）就不能出发 / 自动探索停止
  HEAL_STEP: 0,      // 每走一步恢复生命、法力上限的比例（0.02 = 每步 2%；0 = 只靠宗门秘法恢复）
  // 每次探索固定遇到的事件数量（其余步数无事发生，顺序随机）：
  MONSTERS: 10,      // 普通怪个数
  ELITES: 3,         // 精英怪个数
  BOSS: 1,           // 首领个数（放在最后几步）
  HERB_MIN: 5,       // 发现灵药次数下限
  HERB_MAX: 10,      // 发现灵药次数上限
  ORE_MIN: 5,        // 发现矿脉次数下限
  ORE_MAX: 10,       // 发现矿脉次数上限
  // 凡界每张地图的灵矿：不用历练就能探索 / 元婴出窍，不遇怪，每步挖得灵石
  //   一次（TIME 步）平均灵石 = 当前地图北域一次探索（全胜）的平均灵石；每步 = 平均 ÷ TIME × 随机(0.5 ~ 1.5)
  KUANG: {
    NAME: "{map}灵矿",                    // {map} = 地图名
    DESC: "灵石矿，挖掘可以获得灵石",
    TIME: 100,                            // 每次走多少步
  },
};
